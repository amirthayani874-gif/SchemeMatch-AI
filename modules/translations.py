def init_language():
    """
    Initialize the global language.
    """

    if "language" not in st.session_state:
        st.session_state["language"] = "English"


def render_language_selector():
    """
    Display the global language selector.
    """

    init_language()

    options = list(LANGUAGES.keys())

    current_language = st.session_state["language"]

    selected_language = st.selectbox(
        t("language"),
        options,
        index=options.index(current_language),
        key="global_language_selector"
    )

    st.session_state["language"] = selected_language

    return selected_language


def t(key):
    """
    Return translated text for the selected language.
    """

    init_language()

    language = st.session_state["language"]

    if key in TRANSLATIONS:

        return TRANSLATIONS[key].get(
            language,
            TRANSLATIONS[key]["English"]
        )

    return key


def opt(value):
    """
    Translate dropdown options for display.

    IMPORTANT:
    The original English value is still returned internally.
    This keeps the existing matching algorithm unchanged.
    """

    init_language()

    language = st.session_state["language"]

    if value in OPTION_TRANSLATIONS:

        return OPTION_TRANSLATIONS[value].get(
            language,
            OPTION_TRANSLATIONS[value]["English"]
        )

    return value


def scheme_text(value):
    """
    Translate scheme-related text while keeping
    original English values internally.
    """

    init_language()

    language = st.session_state["language"]

    if value in SCHEME_TRANSLATIONS:
        return SCHEME_TRANSLATIONS[value].get(
            language,
            SCHEME_TRANSLATIONS[value]["English"]
        )

    return value